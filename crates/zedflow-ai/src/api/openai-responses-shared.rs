fn encode_text_signature_v1(id: &str, phase: Option<TextSignaturePhase>) -> String {
    let mut payload = json!({ "v": 1, "id": id });
    if let Some(phase) = phase {
        payload["phase"] = json!(phase.as_str());
    }
    payload.to_string()
}

fn parse_text_signature(signature: Option<&str>) -> Option<(String, Option<TextSignaturePhase>)> {
    let signature = signature?;
    if signature.starts_with('{')
        && let Ok(parsed) = serde_json::from_str::<TextSignatureV1>(signature)
        && parsed.v == 1
    {
        return Some((parsed.id, parsed.phase));
    }
    Some((signature.to_owned(), None))
}

fn short_hash(str_value: &str) -> String {
    let mut h1 = 0xdead_beefu32;
    let mut h2 = 0x41c6_ce57u32;
    for ch in str_value.encode_utf16() {
        let ch = u32::from(ch);
        h1 = (h1 ^ ch).wrapping_mul(2_654_435_761);
        h2 = (h2 ^ ch).wrapping_mul(1_597_334_677);
    }
    h1 = (h1 ^ (h1 >> 16)).wrapping_mul(2_246_822_507)
        ^ (h2 ^ (h2 >> 13)).wrapping_mul(3_266_489_909);
    h2 = (h2 ^ (h2 >> 16)).wrapping_mul(2_246_822_507)
        ^ (h1 ^ (h1 >> 13)).wrapping_mul(3_266_489_909);
    format!("{}{}", to_base36(h2), to_base36(h1))
}

fn to_base36(mut value: u32) -> String {
    if value == 0 {
        return "0".to_owned();
    }
    let mut chars = Vec::new();
    while value > 0 {
        let digit = (value % 36) as u8;
        let ch = if digit < 10 {
            b'0' + digit
        } else {
            b'a' + (digit - 10)
        };
        chars.push(char::from(ch));
        value /= 36;
    }
    chars.iter().rev().collect()
}

fn normalize_id_part(part: &str) -> String {
    let sanitized: String = part
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' || ch == '-' {
                ch
            } else {
                '_'
            }
        })
        .collect();
    let normalized = if sanitized.len() > 64 {
        sanitized[..64].to_owned()
    } else {
        sanitized
    };
    normalized.trim_end_matches('_').to_owned()
}

fn parse_streaming_json(partial_json: &str) -> Value {
    if partial_json.trim().is_empty() {
        return json!({});
    }
    serde_json::from_str(partial_json).unwrap_or_else(|_| json!({}))
}

fn calculate_cost(model: &Model, usage: &mut Usage) -> UsageCost {
    let long_write = usage.cache_write_1h.unwrap_or(0) as f64;
    let short_write = usage
        .cache_write
        .saturating_sub(usage.cache_write_1h.unwrap_or(0)) as f64;
    usage.cost.input = (model.cost.input / 1_000_000.0) * usage.input as f64;
    usage.cost.output = (model.cost.output / 1_000_000.0) * usage.output as f64;
    usage.cost.cache_read = (model.cost.cache_read / 1_000_000.0) * usage.cache_read as f64;
    usage.cost.cache_write =
        (model.cost.cache_write * short_write + model.cost.input * 2.0 * long_write) / 1_000_000.0;
    usage.cost.total =
        usage.cost.input + usage.cost.output + usage.cost.cache_read + usage.cost.cache_write;
    usage.cost
}

fn has_image_input(model: &Model) -> bool {
    model.input.iter().any(|input| input == "image")
}

fn replace_images_with_placeholder(
    content: &[InputContent],
    placeholder: &str,
) -> Vec<InputContent> {
    let mut result = Vec::new();
    let mut previous_was_placeholder = false;
    for block in content {
        match block {
            InputContent::Image(_) => {
                if !previous_was_placeholder {
                    result.push(InputContent::Text(TextContent {
                        text: placeholder.to_owned(),
                        text_signature: None,
                    }));
                }
                previous_was_placeholder = true;
            }
            InputContent::Text(text) => {
                result.push(InputContent::Text(text.clone()));
                previous_was_placeholder = text.text == placeholder;
            }
        }
    }
    result
}

fn transform_messages(
    messages: &[Message],
    model: &Model,
    allowed_tool_call_providers: &HashSet<String>,
) -> Vec<Message> {
    const NON_VISION_USER_IMAGE_PLACEHOLDER: &str =
        "(image omitted: model does not support images)";
    const NON_VISION_TOOL_IMAGE_PLACEHOLDER: &str =
        "(tool image omitted: model does not support images)";

    let mut transformed = Vec::with_capacity(messages.len());
    let mut tool_call_id_map: HashMap<String, String> = HashMap::new();
    let allow_provider_ids = allowed_tool_call_providers.contains(&model.provider);

    for msg in messages {
        match msg {
            Message::User(user) => {
                let mut user = user.clone();
                if !has_image_input(model)
                    && let UserContent::Parts(parts) = &user.content
                {
                    user.content = UserContent::Parts(replace_images_with_placeholder(
                        parts,
                        NON_VISION_USER_IMAGE_PLACEHOLDER,
                    ));
                }
                transformed.push(Message::User(user));
            }
            Message::ToolResult(tool_result) => {
                let mut tool_result = tool_result.clone();
                if let Some(id) = tool_call_id_map.get(&tool_result.tool_call_id) {
                    tool_result.tool_call_id.clone_from(id);
                }
                if !has_image_input(model) {
                    tool_result.content = replace_images_with_placeholder(
                        &tool_result.content,
                        NON_VISION_TOOL_IMAGE_PLACEHOLDER,
                    );
                }
                transformed.push(Message::ToolResult(tool_result));
            }
            Message::Assistant(assistant) => {
                if matches!(
                    assistant.stop_reason,
                    StopReason::Error | StopReason::Aborted
                ) {
                    continue;
                }
                let is_same_model = assistant.provider == model.provider
                    && assistant.api == model.api
                    && assistant.model == model.id;
                let mut assistant = assistant.clone();
                let source = assistant.clone();
                assistant.content = assistant
                    .content
                    .into_iter()
                    .filter_map(|block| match block {
                        AssistantContent::Thinking(thinking) => {
                            if thinking.redacted {
                                return is_same_model
                                    .then_some(AssistantContent::Thinking(thinking));
                            }
                            if is_same_model && thinking.thinking_signature.is_some() {
                                return Some(AssistantContent::Thinking(thinking));
                            }
                            if thinking.thinking.trim().is_empty() {
                                return None;
                            }
                            if is_same_model {
                                Some(AssistantContent::Thinking(thinking))
                            } else {
                                Some(AssistantContent::Text(TextContent {
                                    text: thinking.thinking,
                                    text_signature: None,
                                }))
                            }
                        }
                        AssistantContent::Text(mut text) => {
                            if !is_same_model {
                                text.text_signature = None;
                            }
                            Some(AssistantContent::Text(text))
                        }
                        AssistantContent::ToolCall(mut tool_call) => {
                            if !is_same_model {
                                tool_call.thought_signature = None;
                                let normalized = normalize_tool_call_id(
                                    &tool_call.id,
                                    model,
                                    &source,
                                    allow_provider_ids,
                                );
                                if normalized != tool_call.id {
                                    tool_call_id_map
                                        .insert(tool_call.id.clone(), normalized.clone());
                                    tool_call.id = normalized;
                                }
                            }
                            Some(AssistantContent::ToolCall(tool_call))
                        }
                    })
                    .collect();
                transformed.push(Message::Assistant(assistant));
            }
        }
    }

    insert_synthetic_tool_results(transformed)
}

fn normalize_tool_call_id(
    id: &str,
    model: &Model,
    source: &AssistantMessage,
    allow_provider_ids: bool,
) -> String {
    if !allow_provider_ids {
        return normalize_id_part(id);
    }
    let Some((call_id, item_id)) = id.split_once('|') else {
        return normalize_id_part(id);
    };
    let normalized_call_id = normalize_id_part(call_id);
    let is_foreign_tool_call = source.provider != model.provider || source.api != model.api;
    let mut normalized_item_id = if is_foreign_tool_call {
        let normalized = format!("fc_{}", short_hash(item_id));
        if normalized.len() > 64 {
            normalized[..64].to_owned()
        } else {
            normalized
        }
    } else {
        normalize_id_part(item_id)
    };
    if !normalized_item_id.starts_with("fc_") {
        normalized_item_id = normalize_id_part(&format!("fc_{normalized_item_id}"));
    }
    format!("{normalized_call_id}|{normalized_item_id}")
}

fn insert_synthetic_tool_results(messages: Vec<Message>) -> Vec<Message> {
    let mut result = Vec::with_capacity(messages.len());
    let mut pending_tool_calls: Vec<ToolCall> = Vec::new();
    let mut existing_tool_result_ids: HashSet<String> = HashSet::new();

    fn insert_pending(
        result: &mut Vec<Message>,
        pending_tool_calls: &mut Vec<ToolCall>,
        existing_tool_result_ids: &mut HashSet<String>,
    ) {
        for tool_call in pending_tool_calls.drain(..) {
            if !existing_tool_result_ids.contains(&tool_call.id) {
                result.push(Message::ToolResult(ToolResultMessage {
                    tool_call_id: tool_call.id,
                    tool_name: tool_call.name,
                    content: vec![InputContent::Text(TextContent {
                        text: "No result provided".to_owned(),
                        text_signature: None,
                    })],
                    is_error: true,
                }));
            }
        }
        existing_tool_result_ids.clear();
    }

    for msg in messages {
        match &msg {
            Message::Assistant(assistant) => {
                insert_pending(
                    &mut result,
                    &mut pending_tool_calls,
                    &mut existing_tool_result_ids,
                );
                pending_tool_calls = assistant
                    .content
                    .iter()
                    .filter_map(|block| match block {
                        AssistantContent::ToolCall(tool_call) => Some(tool_call.clone()),
                        _ => None,
                    })
                    .collect();
                result.push(msg);
            }
            Message::ToolResult(tool_result) => {
                existing_tool_result_ids.insert(tool_result.tool_call_id.clone());
                result.push(msg);
            }
            Message::User(_) => {
                insert_pending(
                    &mut result,
                    &mut pending_tool_calls,
                    &mut existing_tool_result_ids,
                );
                result.push(msg);
            }
        }
    }
    insert_pending(
        &mut result,
        &mut pending_tool_calls,
        &mut existing_tool_result_ids,
    );
    result
}

/// Converts Pi messages into OpenAI Responses input items.
#[must_use]
pub fn convert_responses_messages(
    model: &Model,
    context: &Context,
    allowed_tool_call_providers: &HashSet<String>,
    options: Option<ConvertResponsesMessagesOptions>,
) -> ResponseInput {
    let mut messages = ResponseInput::new();
    let transformed_messages =
        transform_messages(&context.messages, model, allowed_tool_call_providers);

    let include_system_prompt = options
        .and_then(|options| options.include_system_prompt)
        .unwrap_or(true);
    if include_system_prompt && let Some(system_prompt) = &context.system_prompt {
        let supports_developer_role = model
            .compat
            .as_ref()
            .and_then(|compat| compat.supports_developer_role)
            .unwrap_or(true);
        let role = if model.reasoning && supports_developer_role {
            "developer"
        } else {
            "system"
        };
        messages.push(json!({ "role": role, "content": sanitize_surrogates(system_prompt) }));
    }

    for (msg_index, msg) in transformed_messages.iter().enumerate() {
        match msg {
            Message::User(user) => match &user.content {
                UserContent::Text(text) => messages.push(json!({
                    "role": "user",
                    "content": [{ "type": "input_text", "text": sanitize_surrogates(text) }]
                })),
                UserContent::Parts(parts) => {
                    let content: Vec<Value> = parts
                        .iter()
                        .map(|item| match item {
                            InputContent::Text(text) => json!({
                                "type": "input_text",
                                "text": sanitize_surrogates(&text.text)
                            }),
                            InputContent::Image(image) => json!({
                                "type": "input_image",
                                "detail": "auto",
                                "image_url": format!("data:{};base64,{}", image.mime_type, image.data)
                            }),
                        })
                        .collect();
                    if !content.is_empty() {
                        messages.push(json!({ "role": "user", "content": content }));
                    }
                }
            },
            Message::Assistant(assistant) => {
                let output = convert_assistant_message(model, assistant, msg_index);
                messages.extend(output);
            }
            Message::ToolResult(tool_result) => {
                messages.push(convert_tool_result_message(model, tool_result));
            }
        }
    }

    messages
}

fn convert_assistant_message(
    model: &Model,
    assistant: &AssistantMessage,
    msg_index: usize,
) -> ResponseInput {
    let is_different_model = assistant.model != model.id
        && assistant.provider == model.provider
        && assistant.api == model.api;
    let mut output = ResponseInput::new();
    let mut text_block_index = 0usize;

    for block in &assistant.content {
        match block {
            AssistantContent::Thinking(thinking) => {
                if let Some(signature) = &thinking.thinking_signature
                    && let Ok(value) = serde_json::from_str(signature)
                {
                    output.push(value);
                }
            }
            AssistantContent::Text(text) => {
                let parsed_signature = parse_text_signature(text.text_signature.as_deref());
                let fallback_message_id = if text_block_index == 0 {
                    format!("msg_pi_{msg_index}")
                } else {
                    format!("msg_pi_{msg_index}_{text_block_index}")
                };
                text_block_index += 1;
                let (mut msg_id, phase) = parsed_signature.unwrap_or((fallback_message_id, None));
                if msg_id.len() > 64 {
                    msg_id = format!("msg_{}", short_hash(&msg_id));
                }
                let mut item = json!({
                    "type": "message",
                    "role": "assistant",
                    "content": [{ "type": "output_text", "text": sanitize_surrogates(&text.text), "annotations": [] }],
                    "status": "completed",
                    "id": msg_id,
                });
                if let Some(phase) = phase {
                    item["phase"] = json!(phase.as_str());
                }
                output.push(item);
            }
            AssistantContent::ToolCall(tool_call) => {
                let (call_id, mut item_id) = tool_call
                    .id
                    .split_once('|')
                    .map(|(call, item)| (call.to_owned(), Some(item.to_owned())))
                    .unwrap_or_else(|| (tool_call.id.clone(), None));
                if is_different_model && item_id.as_ref().is_some_and(|id| id.starts_with("fc_")) {
                    item_id = None;
                }
                let mut item = json!({
                    "type": "function_call",
                    "call_id": call_id,
                    "name": tool_call.name,
                    "arguments": tool_call.arguments.to_string(),
                });
                if let Some(item_id) = item_id {
                    item["id"] = json!(item_id);
                }
                output.push(item);
            }
        }
    }

    output
}

fn convert_tool_result_message(model: &Model, tool_result: &ToolResultMessage) -> Value {
    let text_result = tool_result
        .content
        .iter()
        .filter_map(|content| match content {
            InputContent::Text(text) => Some(text.text.as_str()),
            InputContent::Image(_) => None,
        })
        .collect::<Vec<_>>()
        .join("\n");
    let has_images = tool_result
        .content
        .iter()
        .any(|content| matches!(content, InputContent::Image(_)));
    let has_text = !text_result.is_empty();
    let call_id = tool_result
        .tool_call_id
        .split_once('|')
        .map(|(call_id, _)| call_id)
        .unwrap_or(&tool_result.tool_call_id);

    let output = if has_images && has_image_input(model) {
        let mut content_parts = Vec::new();
        if has_text {
            content_parts
                .push(json!({ "type": "input_text", "text": sanitize_surrogates(&text_result) }));
        }
        for block in &tool_result.content {
            if let InputContent::Image(image) = block {
                content_parts.push(json!({
                    "type": "input_image",
                    "detail": "auto",
                    "image_url": format!("data:{};base64,{}", image.mime_type, image.data)
                }));
            }
        }
        Value::Array(content_parts)
    } else {
        json!(sanitize_surrogates(if has_text {
            &text_result
        } else if has_images {
            "(see attached image)"
        } else {
            "(no tool output)"
        }))
    };

    json!({ "type": "function_call_output", "call_id": call_id, "output": output })
}

/// Converts Pi tools into OpenAI Responses function tools.
#[must_use]
pub fn convert_responses_tools(
    tools: &[Tool],
    options: Option<ConvertResponsesToolsOptions>,
) -> Vec<OpenAITool> {
    let strict = options.and_then(|options| options.strict).unwrap_or(false);
    tools
        .iter()
        .map(|tool| {
            json!({
                "type": "function",
                "name": tool.name,
                "description": tool.description,
                "parameters": tool.parameters,
                "strict": strict,
            })
        })
        .collect()
}

/// Stateful single-pass processor for OpenAI Responses stream events.
///
/// Pi consumes its async iterable once while retaining output-slot and partial tool-call state.
/// This processor preserves that behavior for transports that decode SSE incrementally.
#[derive(Debug, Default)]
pub(crate) struct ResponsesStreamProcessor {
    saw_terminal_response_event: bool,
    output_slots: HashMap<usize, ResponsesOutputSlot>,
    streaming_tool_calls: HashMap<usize, StreamingToolCall>,
}

impl ResponsesStreamProcessor {
    /// Processes one provider event and returns whether a terminal response event was seen.
    pub(crate) fn push(
        &mut self,
        event: ResponseStreamEvent,
        output: &mut AssistantMessage,
        stream: &mut AssistantMessageEventStream,
        model: &Model,
        options: Option<&OpenAIResponsesStreamOptions>,
    ) -> Result<bool> {
        match event {
            ResponseStreamEvent::ResponseCreated { response } => {
                output.response_id = response.id;
            }
            ResponseStreamEvent::ResponseOutputItemAdded { output_index, item } => {
                create_slot(
                    output_index,
                    &item,
                    output,
                    stream,
                    &mut self.output_slots,
                    &mut self.streaming_tool_calls,
                );
            }
            ResponseStreamEvent::ResponseReasoningSummaryTextDelta {
                output_index,
                delta,
            }
            | ResponseStreamEvent::ResponseReasoningTextDelta {
                output_index,
                delta,
            } => {
                if let Some(slot) = get_slot(&self.output_slots, output_index, SlotKind::Thinking) {
                    append_thinking(output, slot.content_index, &delta);
                    stream.push(AssistantMessageEvent::ThinkingDelta {
                        content_index: slot.content_index,
                        delta,
                        partial: output.clone(),
                    });
                }
            }
            ResponseStreamEvent::ResponseReasoningSummaryPartDone { output_index } => {
                if let Some(slot) = get_slot(&self.output_slots, output_index, SlotKind::Thinking) {
                    append_thinking(output, slot.content_index, "\n\n");
                    stream.push(AssistantMessageEvent::ThinkingDelta {
                        content_index: slot.content_index,
                        delta: "\n\n".to_owned(),
                        partial: output.clone(),
                    });
                }
            }
            ResponseStreamEvent::ResponseOutputTextDelta {
                output_index,
                delta,
            }
            | ResponseStreamEvent::ResponseRefusalDelta {
                output_index,
                delta,
            } => {
                if let Some(slot) = get_slot(&self.output_slots, output_index, SlotKind::Text) {
                    append_text(output, slot.content_index, &delta);
                    stream.push(AssistantMessageEvent::TextDelta {
                        content_index: slot.content_index,
                        delta,
                        partial: output.clone(),
                    });
                }
            }
            ResponseStreamEvent::ResponseFunctionCallArgumentsDelta {
                output_index,
                delta,
            } => {
                if let Some(slot) = get_slot(&self.output_slots, output_index, SlotKind::ToolCall)
                    && let Some(call) = self.streaming_tool_calls.get_mut(&output_index)
                {
                    call.partial_json.push_str(&delta);
                    call.tool_call.arguments = parse_streaming_json(&call.partial_json);
                    set_tool_call(output, slot.content_index, call.tool_call.clone());
                    stream.push(AssistantMessageEvent::ToolCallDelta {
                        content_index: slot.content_index,
                        delta,
                        partial: output.clone(),
                    });
                }
            }
            ResponseStreamEvent::ResponseFunctionCallArgumentsDone {
                output_index,
                arguments,
            } => {
                if let Some(slot) = get_slot(&self.output_slots, output_index, SlotKind::ToolCall)
                    && let Some(call) = self.streaming_tool_calls.get_mut(&output_index)
                {
                    let previous_partial_json = call.partial_json.clone();
                    call.partial_json = arguments.clone();
                    call.tool_call.arguments = parse_streaming_json(&call.partial_json);
                    set_tool_call(output, slot.content_index, call.tool_call.clone());
                    if arguments.starts_with(&previous_partial_json) {
                        let delta = arguments[previous_partial_json.len()..].to_owned();
                        if !delta.is_empty() {
                            stream.push(AssistantMessageEvent::ToolCallDelta {
                                content_index: slot.content_index,
                                delta,
                                partial: output.clone(),
                            });
                        }
                    }
                }
            }
            ResponseStreamEvent::ResponseOutputItemDone { output_index, item } => {
                if !self.output_slots.contains_key(&output_index) {
                    create_slot(
                        output_index,
                        &item,
                        output,
                        stream,
                        &mut self.output_slots,
                        &mut self.streaming_tool_calls,
                    );
                }
                finalize_item(
                    output_index,
                    item,
                    output,
                    stream,
                    &mut self.output_slots,
                    &mut self.streaming_tool_calls,
                );
            }
            ResponseStreamEvent::ResponseCompleted { response }
            | ResponseStreamEvent::ResponseIncomplete { response } => {
                self.saw_terminal_response_event = true;
                finalize_response(response, output, model, options)?;
            }
            ResponseStreamEvent::Error { code, message } => {
                return Err(OpenAIResponsesSharedError::StreamError { code, message });
            }
            ResponseStreamEvent::ResponseFailed { response } => {
                return Err(OpenAIResponsesSharedError::ResponseFailed {
                    message: failed_response_message(response.as_ref()),
                });
            }
        }
        Ok(self.saw_terminal_response_event)
    }

    pub(crate) fn finish(&self) -> Result<()> {
        if self.saw_terminal_response_event {
            Ok(())
        } else {
            Err(OpenAIResponsesSharedError::MissingTerminalEvent)
        }
    }
}

/// Processes OpenAI Responses stream events into a Pi assistant message and event stream.
///
/// # Errors
///
/// Returns an error when the provider emits an error/failure event, an unknown response status is
/// encountered, or the event iterator ends before a terminal response event.
pub fn process_responses_stream<I>(
    openai_stream: I,
    output: &mut AssistantMessage,
    stream: &mut AssistantMessageEventStream,
    model: &Model,
    options: Option<&OpenAIResponsesStreamOptions>,
) -> Result<()>
where
    I: IntoIterator<Item = ResponseStreamEvent>,
{
    let mut processor = ResponsesStreamProcessor::default();
    for event in openai_stream {
        processor.push(event, output, stream, model, options)?;
    }
    processor.finish()
}

fn get_slot(
    output_slots: &HashMap<usize, ResponsesOutputSlot>,
    output_index: usize,
    kind: SlotKind,
) -> Option<ResponsesOutputSlot> {
    output_slots
        .get(&output_index)
        .copied()
        .filter(|slot| slot.kind == kind)
}

fn create_slot(
    output_index: usize,
    item: &ResponseOutputItem,
    output: &mut AssistantMessage,
    stream: &mut AssistantMessageEventStream,
    output_slots: &mut HashMap<usize, ResponsesOutputSlot>,
    streaming_tool_calls: &mut HashMap<usize, StreamingToolCall>,
) -> Option<ResponsesOutputSlot> {
    let (kind, content) = match item {
        ResponseOutputItem::Reasoning { .. } => (
            SlotKind::Thinking,
            AssistantContent::Thinking(ThinkingContent::default()),
        ),
        ResponseOutputItem::Message { .. } => (
            SlotKind::Text,
            AssistantContent::Text(TextContent::default()),
        ),
        ResponseOutputItem::FunctionCall {
            id,
            call_id,
            name,
            arguments,
        } => {
            let tool_call = ToolCall {
                id: format!("{}|{}", call_id, id.as_deref().unwrap_or_default()),
                name: name.clone(),
                arguments: json!({}),
                thought_signature: None,
            };
            streaming_tool_calls.insert(
                output_index,
                StreamingToolCall {
                    tool_call: tool_call.clone(),
                    partial_json: arguments.clone(),
                },
            );
            (SlotKind::ToolCall, AssistantContent::ToolCall(tool_call))
        }
        ResponseOutputItem::Other { .. } => return None,
    };
    output.content.push(content);
    let slot = ResponsesOutputSlot {
        kind,
        content_index: output.content.len() - 1,
    };
    output_slots.insert(output_index, slot);
    match kind {
        SlotKind::Thinking => stream.push(AssistantMessageEvent::ThinkingStart {
            content_index: slot.content_index,
            partial: output.clone(),
        }),
        SlotKind::Text => stream.push(AssistantMessageEvent::TextStart {
            content_index: slot.content_index,
            partial: output.clone(),
        }),
        SlotKind::ToolCall => stream.push(AssistantMessageEvent::ToolCallStart {
            content_index: slot.content_index,
            partial: output.clone(),
        }),
    }
    Some(slot)
}

fn append_thinking(output: &mut AssistantMessage, content_index: usize, delta: &str) {
    if let Some(AssistantContent::Thinking(block)) = output.content.get_mut(content_index) {
        block.thinking.push_str(delta);
    }
}

fn append_text(output: &mut AssistantMessage, content_index: usize, delta: &str) {
    if let Some(AssistantContent::Text(block)) = output.content.get_mut(content_index) {
        block.text.push_str(delta);
    }
}

fn set_tool_call(output: &mut AssistantMessage, content_index: usize, tool_call: ToolCall) {
    if let Some(AssistantContent::ToolCall(block)) = output.content.get_mut(content_index) {
        *block = tool_call;
    }
}

fn finalize_item(
    output_index: usize,
    item: ResponseOutputItem,
    output: &mut AssistantMessage,
    stream: &mut AssistantMessageEventStream,
    output_slots: &mut HashMap<usize, ResponsesOutputSlot>,
    streaming_tool_calls: &mut HashMap<usize, StreamingToolCall>,
) {
    let Some(slot) = output_slots.get(&output_index).copied() else {
        return;
    };
    match item {
        ResponseOutputItem::Reasoning {
            summary,
            content,
            raw,
        } if slot.kind == SlotKind::Thinking => {
            if let Some(AssistantContent::Thinking(block)) =
                output.content.get_mut(slot.content_index)
            {
                let summary_text = summary
                    .iter()
                    .map(|part| part.text.as_str())
                    .collect::<Vec<_>>()
                    .join("\n\n");
                let content_text = content
                    .iter()
                    .map(|part| part.text.as_str())
                    .collect::<Vec<_>>()
                    .join("\n\n");
                if !summary_text.is_empty() {
                    block.thinking = summary_text;
                } else if !content_text.is_empty() {
                    block.thinking = content_text;
                }
                block.thinking_signature = Some(raw.to_string());
                let content = block.thinking.clone();
                stream.push(AssistantMessageEvent::ThinkingEnd {
                    content_index: slot.content_index,
                    content,
                    partial: output.clone(),
                });
            }
            output_slots.remove(&output_index);
        }
        ResponseOutputItem::Message { id, phase, content } if slot.kind == SlotKind::Text => {
            if let Some(AssistantContent::Text(block)) = output.content.get_mut(slot.content_index)
            {
                block.text = content
                    .iter()
                    .map(|part| {
                        if part.r#type == "output_text" {
                            part.text.as_deref().unwrap_or_default()
                        } else {
                            part.refusal.as_deref().unwrap_or_default()
                        }
                    })
                    .collect::<String>();
                block.text_signature = Some(encode_text_signature_v1(&id, phase));
                let content = block.text.clone();
                stream.push(AssistantMessageEvent::TextEnd {
                    content_index: slot.content_index,
                    content,
                    partial: output.clone(),
                });
            }
            output_slots.remove(&output_index);
        }
        ResponseOutputItem::FunctionCall { arguments, .. } if slot.kind == SlotKind::ToolCall => {
            if let Some(mut call) = streaming_tool_calls.remove(&output_index) {
                let final_json = if arguments.is_empty() {
                    if call.partial_json.is_empty() {
                        "{}".to_owned()
                    } else {
                        call.partial_json
                    }
                } else {
                    arguments
                };
                call.tool_call.arguments = parse_streaming_json(&final_json);
                set_tool_call(output, slot.content_index, call.tool_call.clone());
                stream.push(AssistantMessageEvent::ToolCallEnd {
                    content_index: slot.content_index,
                    tool_call: call.tool_call,
                    partial: output.clone(),
                });
            }
            output_slots.remove(&output_index);
        }
        _ => {}
    }
}

fn finalize_response(
    response: Response,
    output: &mut AssistantMessage,
    model: &Model,
    options: Option<&OpenAIResponsesStreamOptions>,
) -> Result<()> {
    if response.id.is_some() {
        output.response_id = response.id;
    }
    if let Some(usage) = response.usage {
        let cached_tokens = usage
            .input_tokens_details
            .map(|details| details.cached_tokens)
            .unwrap_or(0);
        output.usage = Usage {
            input: usage.input_tokens.saturating_sub(cached_tokens),
            output: usage.output_tokens,
            cache_read: cached_tokens,
            cache_write: 0,
            cache_write_1h: None,
            reasoning: Some(
                usage
                    .output_tokens_details
                    .map(|details| details.reasoning_tokens)
                    .unwrap_or(0),
            ),
            total_tokens: usage.total_tokens,
            cost: UsageCost::default(),
        };
    }
    calculate_cost(model, &mut output.usage);
    if let Some(options) = options
        && let Some(apply) = options.apply_service_tier_pricing
    {
        let tier = if let Some(resolve) = options.resolve_service_tier {
            resolve(
                response.service_tier.as_deref(),
                options.service_tier.as_deref(),
            )
        } else {
            response
                .service_tier
                .or_else(|| options.service_tier.clone())
        };
        apply(&mut output.usage, tier.as_deref());
    }
    output.stop_reason = map_stop_reason(response.status)?;
    if output
        .content
        .iter()
        .any(|block| matches!(block, AssistantContent::ToolCall(_)))
        && output.stop_reason == StopReason::Stop
    {
        output.stop_reason = StopReason::ToolUse;
    }
    Ok(())
}

fn failed_response_message(response: Option<&Response>) -> String {
    if let Some(error) = response.and_then(|response| response.error.as_ref()) {
        return format!(
            "{}: {}",
            error.code.as_deref().unwrap_or("unknown"),
            error.message.as_deref().unwrap_or("no message")
        );
    }
    if let Some(reason) = response
        .and_then(|response| response.incomplete_details.as_ref())
        .and_then(|details| details.reason.as_ref())
    {
        return format!("incomplete: {reason}");
    }
    "Unknown error (no error details in response)".to_owned()
}

fn map_stop_reason(status: Option<ResponseStatus>) -> Result<StopReason> {
    let Some(status) = status else {
        return Ok(StopReason::Stop);
    };
    match status {
        ResponseStatus::Completed | ResponseStatus::InProgress | ResponseStatus::Queued => {
            Ok(StopReason::Stop)
        }
        ResponseStatus::Incomplete => Ok(StopReason::Length),
        ResponseStatus::Failed | ResponseStatus::Cancelled => Ok(StopReason::Error),
    }
}

