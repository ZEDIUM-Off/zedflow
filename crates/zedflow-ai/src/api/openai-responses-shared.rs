/// Result type for OpenAI Responses shared helpers.
pub type Result<T> = std::result::Result<T, OpenAIResponsesSharedError>;

/// Errors returned by OpenAI Responses shared helpers.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum OpenAIResponsesSharedError {
    /// The upstream stream emitted an error event.
    StreamError { code: String, message: String },
    /// The upstream response failed.
    ResponseFailed { message: String },
    /// The stream ended before a terminal response event.
    MissingTerminalEvent,
    /// A response status was not known to this port.
    UnhandledStopReason { status: String },
}

impl fmt::Display for OpenAIResponsesSharedError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::StreamError { code, message } => write!(f, "Error Code {code}: {message}"),
            Self::ResponseFailed { message } => f.write_str(message),
            Self::MissingTerminalEvent => {
                f.write_str("OpenAI Responses stream ended before a terminal response event")
            }
            Self::UnhandledStopReason { status } => write!(f, "Unhandled stop reason: {status}"),
        }
    }
}

impl StdError for OpenAIResponsesSharedError {}

