test('the new Harness can run without a bridge and resets its absent routing result before model preparation',async({request})=>{
  const flow=harnessTemplate()
  flow.name=`Harness autonome sans bridge ${Date.now()}`
  const model=flow.nodes.find(node=>node.id==='model')!
  model.data.config.modelBinding='fixed';model.data.config.provider='fixture';model.data.config.model='fixture'
  flow.nodes.find(node=>node.id==='start')!.data.config.exports.contract.inferenceNodes.model.model={kind:'fixed',provider:'fixture',model:'fixture'}
  const file=await saveFlow(request,flow)
  const response=await request.post('/api/runs',{data:{flowKey:file.key,flowHash:file.hash,input:{input:'Continuer sans route externe',routeResult:'Ancien résultat à ne pas réutiliser'}}})
  expect(response.ok(),await response.text()).toBeTruthy()
  const ack=await response.json(),run=await waitRun(request,ack.id,'waiting')
  const completed=run.activities!.filter(activity=>activity.status==='completed')
  const preparations=completed.filter(activity=>['dispatch','context','model'].includes(activity.node)).map(activity=>activity.node)
  expect(preparations.length).toBeGreaterThanOrEqual(3)
  expect(preparations.length%3).toBe(0)
  for(let index=0;index<preparations.length;index+=3)expect(preparations.slice(index,index+3)).toEqual(['dispatch','context','model'])
  expect(run.state.routeResult).toBe('')
  expect(run.messages.at(-1)?.text).toContain('Continuer sans route externe')
})

test('converting a parallel join preserves the default all-predecessors barrier before context preparation',async({request})=>{
  const converted=parallelJoinFixture()
  expect(converted.nodes.find(node=>node.id==='context')!.data.config.fanIn).toBe('all')
  const file=await saveFlow(request,converted)
  const response=await request.post('/api/runs',{data:{flowKey:file.key,flowHash:file.hash,input:{input:'Attendre les deux branches'}}})
  expect(response.ok(),await response.text()).toBeTruthy()
  const ack=await response.json(),run=await waitRun(request,ack.id,'completed')
  const completed=(run.activities||[]).filter(activity=>activity.status==='completed')
  const preparation=completed.filter(activity=>activity.kind==='context'),prediction=completed.filter(activity=>activity.kind==='model')
  expect(preparation).toHaveLength(1)
  expect(prediction).toHaveLength(1)
  for(const branch of ['fast','slow'])expect(completed.find(activity=>activity.node===branch)!.endedSeq).toBeLessThan(preparation[0].startedSeq!)
  expect(preparation[0].endedSeq).toBeLessThan(prediction[0].startedSeq!)
})

test('the actual starter commits a context passage before each prediction and survives a new turn',async({request})=>{
  const flow=template(true)
  flow.name=`Contexte puis modèle ${Date.now()}`
  const file=await saveFlow(request,flow)
  const response=await request.post('/api/runs',{data:{flowKey:file.key,flowHash:file.hash,input:{input:'Premier passage explicite'}}})
  expect(response.ok(),await response.text()).toBeTruthy()
  const ack=await response.json(),first=await waitRun(request,ack.id,'waiting')
  const steps=(first.activities||[]).filter(item=>item.status==='completed'&&['context','model'].includes(item.kind))
  expect(steps.map(item=>item.kind)).toEqual(['context','model'])
  expect(steps[0].endedSeq).toBeLessThan(steps[1].startedSeq!)
  expect(first.messages.at(-1)?.text).toContain('Premier passage explicite')
  expect(first.composition.nodes.find(node=>node.id==='context')!.data.config.contextProgram).toBeTruthy()
  expect(first.composition.nodes.find(node=>node.id==='model')!.data.config.contextProgram).toBeUndefined()
  const answer=await request.post(`/api/runs/${ack.id}/answer`,{data:{waitId:first.wait!.id,value:'Deuxième passage explicite'}})
  expect(answer.ok(),await answer.text()).toBeTruthy()
  await expect.poll(async()=>{const run=await (await request.get(`/api/runs/${ack.id}`)).json();return run.status==='waiting'&&run.wait?.id!==first.wait!.id}).toBe(true)
  const second=await (await request.get(`/api/runs/${ack.id}`)).json()
  expect(second.activities.filter((item:any)=>item.status==='completed'&&['context','model'].includes(item.kind)).map((item:any)=>item.kind)).toEqual(['context','model','context','model'])
  expect(second.messages.at(-1)?.text).toContain('Deuxième passage explicite')
  expect(new Set(second.timeline.map((item:any)=>item.id)).size).toBe(second.timeline.length)
})
