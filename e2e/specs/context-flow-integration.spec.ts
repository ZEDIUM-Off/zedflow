async function authoring(page: Page, composition: Composition) {
  let saved = structuredClone(composition)
  let savedWorkspace: string | undefined
  const file = (): FlowFile => ({key:saved.id,id:saved.id,name:saved.name,composition:saved,path:`/fixture/.zedflow/flows/${saved.id}.rs`,scope:'workspace',workspaceId:'pair-workspace',hash:'fixture-hash',diagnostics:[]})
  await page.route('**/api/**', async route => {
    const request=route.request(),path=new URL(request.url()).pathname.replace('/api','')
    const respond=(value:unknown)=>route.fulfill({contentType:'application/json',body:JSON.stringify(value)})
    if(path==='/health')return respond({defaultWorkspaceId:'pair-workspace',workspace:{host:'fixture',path:'/fixture'}})
    if(path==='/workspaces')return respond([{id:'pair-workspace',name:'Fixture',path:'/fixture',open:true},{id:'other-workspace',name:'Autre workspace',path:'/other',open:true}])
    if(path==='/runs')return respond([])
    if(path==='/context')return respond({instructions:[],skills:[],diagnostics:[]})
    if(path==='/context-strategies')return respond([{key:'harness-default',hash:'context-hash',path:'/fixture/.zedflow/context/harness-default.rs',strategy:{version:2,id:'harness-default',name:'Contexte du workspace',requirements:{instructions:{kind:'text'}},capabilities:[],program:[]},diagnostics:[]}])
    if(path==='/flows'&&request.method()==='POST'){const body=request.postDataJSON();saved=body.composition;savedWorkspace=body.workspaceId;return respond(file())}
    if(path==='/flows')return respond(new URL(request.url()).searchParams.get('workspaceId')==='other-workspace'?[]:[file()])
    if(path.startsWith('/flows/'))return respond(file())
    if(path==='/models')return respond({models:[{provider:'fixture',id:'fixture',label:'Fixture',reasoningLevels:[]}]})
    if(path==='/rtc/config'||path.endsWith('/events'))return route.fulfill({status:503,body:'HTTP fixture'})
    return respond([])
  })
  await page.goto('/')
  await expect(page.getByText('Daemon connecté',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Conception',exact:true}).click()
  await page.locator('.flow-file-open').click()
  await expect(page.locator('.canvas .vue-flow__node')).toHaveCount(composition.nodes.length)
  return Object.assign(()=>saved,{workspace:()=>savedWorkspace})
}

