async function studio(page: Page) {
  await page.goto('/')
  await expect(page.getByText('Daemon connecté', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Conception', exact: true }).click()
  await page.getByRole('navigation', { name: 'Espace de conception' }).getByRole('button', { name: 'Contexte', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Studio de contexte' })).toBeVisible()
  await page.getByRole('button', { name: 'Créer une stratégie', exact: true }).click()
  return page.locator('.context-studio:not(.bridge-studio)')
}
async function addBlock(page: Page, container: ReturnType<Page['locator']>, kind: 'Groupe' | 'Fragment' | 'Condition') {
  await container.getByRole('button', { name: /Ajouter un bloc$/ }).last().click()
  const label = { Groupe: 'Groupe', Fragment: 'Ajouter au contexte', Condition: 'Si… Alors… Sinon…' }[kind]
  await page.getByRole('menuitem', { name: new RegExp(`^${label}`) }).click()
}
async function declareTextSource(page: Page, panel: Locator, name: string) {
  await panel.getByRole('button', { name: 'Ajouter des types', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Ajouter des types de sources', exact: true })
  await dialog.getByText('Définir un type personnalisé', { exact: true }).click()
  await dialog.getByLabel('Nom du type personnalisé', { exact: true }).fill(name)
  await dialog.getByLabel('Schéma du type personnalisé', { exact: true }).selectOption('text')
  await dialog.getByRole('button', { name: 'Déclarer ce type', exact: true }).click()
}
async function manualSource(panel: Locator, name: string) {
  const source = panel.locator(`[data-resource="${name}"]`)
  const disclosure = source.locator('.ctx-source-disclosure')
  if (await disclosure.getAttribute('aria-expanded') !== 'true') await disclosure.click()
  const manual = source.locator('details').filter({ hasText: `Fournir ${name} pour l’aperçu` })
  if (await manual.getAttribute('open') === null) await manual.locator('summary').click()
  return source
}
async function expressionDetails(block: Locator) {
  await block.getByRole('button', { name: /^Configurer l’expression : Contenu du fragment/ }).click()
  return block.getByRole('combobox', { name: /^Contenu du fragment ·/ })
}
async function dependencies(panel: Locator) {
  const details = panel.locator('.ctx-studio-dependencies')
  if (await details.getAttribute('open') === null) await details.locator('summary').click()
}
function literal(value: string) { return { kind: 'literal' as const, dataType: { kind: 'text' as const }, value } }

