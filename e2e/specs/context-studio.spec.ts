test('context studio preserves dirty workspace drafts and reports a real external source conflict', async ({ page, request }) => {
  const health = await (await request.get('/api/health')).json()
  const workspaceB = await (await request.post('/api/workspaces', { data: { path: fixturePath('workspace-b') } })).json()
  const strategy: ContextStrategy = { version: 1, id: `context-conflict-${Date.now()}`, name: 'Source en conflit', requirements: {}, capabilities: [], program: [{ kind: 'emit', id: 'fragment', role: 'data', format: 'text', value: literal('Version disque') }] }
  const saved = await request.post('/api/context-strategies', { data: { workspaceId: health.defaultWorkspaceId, strategy } })
  expect(saved.ok(), await saved.text()).toBeTruthy()
  const file: ContextFile = await saved.json()
  const panel = await studio(page)
  await page.locator(`[data-context-key="${file.key}"]`).click()
  await panel.getByRole('textbox', { name: /^Contenu du fragment ·/ }).fill('Brouillon préservé')
  await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(workspaceB.id)
  await expect(panel).toHaveAttribute('data-context-workspace', workspaceB.id)
  await panel.getByLabel('Nom de la stratégie', { exact: true }).fill('Brouillon du workspace B')
  await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(health.defaultWorkspaceId)
  await expect(panel.getByRole('textbox', { name: /^Contenu du fragment ·/ })).toHaveValue('Brouillon préservé')
  await writeFile(file.path, (await readFile(file.path, 'utf8')).replace('Version disque', 'Modification externe'))
  await page.getByRole('button', { name: 'Actualiser les stratégies', exact: true }).click()
  await expect(panel.getByRole('textbox', { name: /^Contenu du fragment ·/ })).toHaveValue('Brouillon préservé')
  await panel.getByRole('button', { name: 'Enregistrer la stratégie', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('Votre brouillon est conservé')
  expect(await readFile(file.path, 'utf8')).toContain('Modification externe')
  await panel.getByRole('button', { name: 'Dupliquer la stratégie', exact: true }).click()
  await panel.getByRole('button', { name: 'Enregistrer la stratégie', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Stratégie enregistrée en Rust')
  const files: ContextFile[] = await (await request.get(`/api/context-strategies?workspaceId=${health.defaultWorkspaceId}`)).json()
  const copy = files.find(item => item.strategy?.name === 'Source en conflit · copie')!
  expect(await readFile(copy.path, 'utf8')).toContain('Brouillon préservé')
  expect(copy.key).not.toBe(file.key)
  await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(workspaceB.id)
  await expect(panel.getByLabel('Nom de la stratégie', { exact: true })).toHaveValue('Brouillon du workspace B')
})

for (const editing of [false, true]) test(`context catalogue arrival ${editing ? 'preserves an ongoing name replacement' : 'opens the default when untouched'}`, async ({ page, request }) => {
  const health = await (await request.get('/api/health')).json()
  const workspaceB = await (await request.post('/api/workspaces', { data: { path: fixturePath('workspace-b') } })).json()
  const panel = await studio(page)
  let release!: () => void, received!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const arrived = new Promise<void>(resolve => { received = resolve })
  await page.route(url => url.pathname === '/api/context-strategies' && url.searchParams.get('workspaceId') === workspaceB.id, async route => {
    const response = await route.fetch()
    received()
    await gate
    await route.fulfill({ response })
  })
  try {
    await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(workspaceB.id)
    await arrived
    await expect(panel).toHaveAttribute('data-context-workspace', workspaceB.id)
    const name = panel.getByLabel('Nom de la stratégie', { exact: true })
    await expect(name).toHaveValue('Nouvelle stratégie')
    if (editing) {
      await expect(name).toBeEditable()
      await name.focus()
      await page.keyboard.press('Control+a')
    }
    release()
    await expect(page.getByRole('button', { name: 'Actualiser les stratégies', exact: true })).toBeEnabled()
    if (editing) {
      await page.keyboard.insertText('Brouillon du workspace B')
      await expect(name).toHaveValue('Brouillon du workspace B')
      await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(health.defaultWorkspaceId)
      await expect(panel).toHaveAttribute('data-context-workspace', health.defaultWorkspaceId)
      await page.getByLabel('Workspace des stratégies', { exact: true }).selectOption(workspaceB.id)
      await expect(name).toHaveValue('Brouillon du workspace B')
      // Explicit navigation still opens the catalogue definition after an edit.
      await page.locator('[data-context-key="workspace-default"]').click()
    }
    await expect(name).toHaveValue('Assistant de workspace')
  } finally { release() }
})

